"""Merge `pip freeze` outputs of several Python versions into one constraints file.

Usage:
    python tools/merge_constraints.py 3.11=freeze-3.11.txt 3.12=freeze-3.12.txt 3.13=freeze-3.13.txt > constraints.txt

A package with the same version everywhere is pinned plainly. A package whose version differs, or
that is installed only on some versions, is pinned per version with an environment marker, so that
pip selects the line that matches the running interpreter.
"""

from __future__ import annotations

import sys

HEADER = """# Exact versions of the full dependency tree, tested together on Python {versions}.
# Install with: pip install -c constraints.txt ".[dev]"
# The supported version ranges are declared in pyproject.toml.
# Generated by tools/merge_constraints.py from one `pip freeze` per Python version."""


def read(path: str) -> dict[str, str]:
    pins = {}
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if line and not line.startswith(("#", "-e")) and "==" in line:
            name, version = line.split("==", 1)
            pins[name] = version
    return pins


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print(__doc__, file=sys.stderr)
        return 2
    freezes = {}
    for arg in argv:
        version, _, path = arg.partition("=")
        freezes[version] = read(path)
    versions = sorted(freezes, key=lambda v: tuple(int(p) for p in v.split(".")))
    lines = [HEADER.format(versions=", ".join(versions))]
    names = sorted({n for pins in freezes.values() for n in pins}, key=str.lower)
    for name in names:
        found = {v: freezes[v].get(name) for v in versions}
        if len(set(found.values())) == 1:
            lines.append(f"{name}=={found[versions[0]]}")
            continue
        for v in versions:
            if found[v] is not None:
                lines.append(f'{name}=={found[v]} ; python_version == "{v}"')
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
